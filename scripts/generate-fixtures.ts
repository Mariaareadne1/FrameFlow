// Generates deterministic test media into test-fixtures/ (git-ignored).
// Run: npm run fixtures
//
// Each "screen recording" is a mock app UI with:
//   - a moving accent block (motion),
//   - text labels,
//   - two time-code patches in the top-left corner whose luminance encodes the source time:
//       patch S (x 24..104, y 24..104): level = floor(t) mod 10        (seconds)
//       patch T (x 120..200, y 24..104): level = floor(t * 10) mod 10  (tenths)
//     luminance = 20 + level * 22, so a decoded frame reveals which source moment it shows.
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { DEMO_SCRIPT, scriptedTrack } from '../tests/support/synthetic.ts'

const root = join(import.meta.dirname, '..')
const out = join(root, 'test-fixtures')
const ffmpeg = join(root, 'node_modules/ffmpeg-static/ffmpeg')
const FONT = '/System/Library/Fonts/Helvetica.ttc'
mkdirSync(out, { recursive: true })

interface Spec {
  name: string
  width: number
  height: number
  duration: number
  fps: number
  audio?: boolean
  cursor?: boolean
}

const specs: Spec[] = [
  { name: 'demo-1920x1200', width: 1920, height: 1200, duration: 30, fps: 60, cursor: true },
  { name: 'short-1280x720', width: 1280, height: 720, duration: 1.5, fps: 30 },
  { name: 'portrait-1080x1920', width: 1080, height: 1920, duration: 6, fps: 30 },
  { name: 'tone-1280x800', width: 1280, height: 800, duration: 8, fps: 30, audio: true },
  // Long recording for performance checks (5 minutes, with cursor telemetry and audio).
  { name: 'long-1920x1200', width: 1920, height: 1200, duration: 300, fps: 60, cursor: true, audio: true },
]

function filterFor(s: Spec): string {
  const w = s.width
  const h = s.height
  const text = existsSync(FONT)
  const label = (t: string, x: number | string, y: number | string, size: number, color: string) =>
    text ? `,drawtext=fontfile=${FONT}:text='${t}':x=${x}:y=${y}:fontsize=${size}:fontcolor=${color}` : ''
  return [
    `drawbox=x=0:y=0:w=${w}:h=${Math.round(h * 0.07)}:color=0x23262f:t=fill`,
    `drawbox=x=0:y=${Math.round(h * 0.07)}:w=${Math.round(w * 0.16)}:h=${h}:color=0xe3e7ef:t=fill`,
    `drawbox=x=${Math.round(w * 0.2)}:y=${Math.round(h * 0.15)}:w=${Math.round(w * 0.35)}:h=${Math.round(h * 0.3)}:color=0xffffff:t=fill`,
    `drawbox=x=${Math.round(w * 0.6)}:y=${Math.round(h * 0.15)}:w=${Math.round(w * 0.35)}:h=${Math.round(h * 0.3)}:color=0xffffff:t=fill`,
    `drawbox=x=${Math.round(w * 0.2)}:y=${Math.round(h * 0.52)}:w=${Math.round(w * 0.75)}:h=${Math.round(h * 0.4)}:color=0xffffff:t=fill`,
    `drawbox=x='${Math.round(w * 0.22)}+${Math.round(w * 0.5)}*(0.5+0.5*sin(t))':y=${Math.round(h * 0.6)}:w=${Math.round(w * 0.2)}:h=${Math.round(h * 0.2)}:color=0x5b7cfa:t=fill`,
  ].join(',') +
    label('FrameFlow Test Fixture', Math.round(w * 0.2), Math.round(h * 0.02), Math.round(h * 0.03), 'white') +
    label('Settings', Math.round(w * 0.02), Math.round(h * 0.12), Math.round(h * 0.022), '0x23262f') +
    label('Create project', Math.round(w * 0.22), Math.round(h * 0.18), Math.round(h * 0.03), '0x23262f') +
    label('%{pts\\:hms}', Math.round(w * 0.62), Math.round(h * 0.18), Math.round(h * 0.03), '0x23262f')
}

for (const s of specs) {
  const file = join(out, `${s.name}.mp4`)
  if (existsSync(file) && !process.argv.includes('--force')) {
    console.log(`[fixtures] exists: ${file}`)
    continue
  }
  const base = `color=c=0xf4f6fa:s=${s.width}x${s.height}:r=${s.fps}:d=${s.duration}`
  // Time-code patches are generated by geq and overlaid in the corner.
  const patchS = `color=c=black:s=80x80:r=${s.fps}:d=${s.duration},format=gray,geq=lum='20+mod(floor(T),10)*22'`
  const patchT = `color=c=black:s=80x80:r=${s.fps}:d=${s.duration},format=gray,geq=lum='20+mod(floor(T*10),10)*22'`
  const args = ['-y', '-v', 'error', '-f', 'lavfi', '-i', base, '-f', 'lavfi', '-i', patchS, '-f', 'lavfi', '-i', patchT]
  if (s.audio) args.push('-f', 'lavfi', '-i', `sine=frequency=440:sample_rate=48000:duration=${s.duration}`)
  args.push(
    '-filter_complex',
    `[0:v]${filterFor(s)}[ui];[1:v]format=yuv420p[ps];[2:v]format=yuv420p[pt];[ui][ps]overlay=24:24[a];[a][pt]overlay=120:24,format=yuv420p[v]`,
    '-map', '[v]',
  )
  if (s.audio) args.push('-map', '3:a', '-c:a', 'aac', '-b:a', '128k')
  args.push('-c:v', 'libx264', '-preset', 'veryfast', '-crf', '16', '-g', String(s.fps), '-movflags', '+faststart', file)
  execFileSync(ffmpeg, args, { stdio: 'inherit' })
  if (s.cursor) {
    // Repeat the 30 s demo script to fill longer recordings.
    const steps = Array.from({ length: Math.ceil(s.duration / 30) }, (_, k) => DEMO_SCRIPT.map((st) => ({ ...st, t: st.t + k * 30 }))).flat()
    writeFileSync(join(out, `${s.name}.cursor.json`), JSON.stringify(scriptedTrack(steps, s.duration)))
  }
  console.log(`[fixtures] ${file}`)
}

// Audio fixture for the Sound tests: 12 s of 880 Hz, as an imported voice-over stand-in.
const toneFile = join(out, 'tone-880.m4a')
if (!existsSync(toneFile) || process.argv.includes('--force')) {
  execFileSync(ffmpeg, ['-y', '-v', 'error', '-f', 'lavfi', '-i', 'sine=frequency=880:sample_rate=48000:duration=12', '-c:a', 'aac', '-b:a', '128k', toneFile], { stdio: 'inherit' })
  console.log(`[fixtures] ${toneFile}`)
}
